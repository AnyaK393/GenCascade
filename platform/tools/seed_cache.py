#!/usr/bin/env python3
"""Semantic cache seeding (guide 5.7). Asks every data/faq.yaml question at level 0, one at a
time, and writes the answers to data/cache_seed.yaml with vetted: false. Read them together,
set vetted: true on the good ones, then reload. The RAG service loads this file at startup and
on every /admin/reset, so the seeded cache is the clean state between episodes.

    platform/.venv/bin/python platform/tools/seed_cache.py            # answer missing questions
    platform/.venv/bin/python platform/tools/seed_cache.py --course DSA101 --regen
    platform/.venv/bin/python platform/tools/seed_cache.py --load     # only reload after vetting
"""

import argparse
import sys
import time
from pathlib import Path

import httpx
import yaml

from smoke import env

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from cs_common.settings import faq_questions  # noqa: E402

DATA = Path(__file__).resolve().parents[1] / "data"
FAQ, SEED = DATA / "faq.yaml", DATA / "cache_seed.yaml"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--host", default="localhost")
    ap.add_argument("--course", help="only this course")
    ap.add_argument("--regen", action="store_true", help="re-answer questions already in the file")
    ap.add_argument("--load", action="store_true", help="skip generation, just reload the file")
    a = ap.parse_args()
    hdr = {"X-CS-Token": env("CS_TOKEN", "dev-token")}
    seed = yaml.safe_load(SEED.read_text()) if SEED.exists() else {}
    seed = seed or {}

    if not a.load:
        faq, hints = yaml.safe_load(FAQ.read_text()), yaml.safe_load((DATA / "hints.yaml").read_text())
        todo = [(c, t, q) for c, topics in faq.items() if not c.startswith("_") and (not a.course or c == a.course)
                for t in topics for q in faq_questions(faq, hints, c, t)]
        done, t_start = 0, time.time()
        with httpx.Client(timeout=60) as http:
            for i, (course, topic, q) in enumerate(todo, 1):
                entries = seed.setdefault(course, [])
                old = next((e for e in entries if e["question"] == q), None)
                if old and not a.regen:
                    continue
                t0 = time.time()
                r = http.post(f"http://{a.host}:8002/admin/answer", headers=hdr,
                              json={"course": course, "question": q, "level": 0})
                if r.status_code != 200:
                    print(f"[{i}/{len(todo)}] FAIL {course}/{topic}: {r.status_code} {r.text[:80]}")
                    continue
                entry = {"topic": topic, "question": q, "answer": r.json()["answer"], "vetted": False}
                if old:
                    entries[entries.index(old)] = entry
                else:
                    entries.append(entry)
                done += 1
                print(f"[{i}/{len(todo)}] {time.time() - t0:4.1f}s {course}/{topic}: {q}")
                if done % 10 == 0:  # save as we go, so an interrupted run keeps its answers
                    SEED.write_text(dump(seed))
        SEED.write_text(dump(seed))
        print(f"answered {done} questions in {time.time() - t_start:.0f} s -> {SEED.relative_to(DATA.parent.parent)}")

    r = httpx.post(f"http://{a.host}:8003/cache/reload", headers=hdr, timeout=30)
    total = sum(len(v) for v in seed.values())
    vetted = sum(e.get("vetted", False) for v in seed.values() for e in v)
    print(f"cache reloaded: {r.json().get('loaded')} entries ({vetted}/{total} vetted)")


def dump(seed: dict) -> str:
    head = "# Generated by tools/seed_cache.py. Set vetted: true on answers you have checked.\n"
    return head + yaml.safe_dump(seed, sort_keys=False, allow_unicode=True, width=100)


if __name__ == "__main__":
    main()
